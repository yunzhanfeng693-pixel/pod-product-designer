export const getColors = (): string[] => {
  const colors = new Set(mockShirts.map(shirt => shirt.color))
  return Array.from(colors)
}

export const getColorName = (color: string): string => {
  const shirt = mockShirts.find(s => s.color === color)
  return shirt?.colorName || color
}

export const getCategories = (): string[] => {
  const categories = new Set(mockShirts.map(shirt => shirt.category))
  return Array.from(categories)
}

export const getShirtsByCategory = (category: string): Shirt[] => {
  return mockShirts.filter(shirt => shirt.category === category)
}

export const getShirtsByColor = (color: string): Shirt[] => {
  return mockShirts.filter(shirt => shirt.color === color)
}
